"""Generate src/study_mcp/cambria_math.py, the table that repairs broken math in PDFs.

When PowerPoint or Word saves an equation to PDF, superscripts and subscripts use small versions
of Cambria Math's glyphs. Those small glyphs have no Unicode character of their own, so the
exporter writes the glyph's number instead. A PDF reader then shows glyph 2869 (a small "1") as
U+0B35, an Odia letter. This script reads the font and records, for every small glyph, the
character it really is and how small it is (1 = superscript/subscript, 2 = one level smaller).

Run on Windows with Office fonts installed:  pip install fonttools && python scripts/gen_cambria_math.py
"""

from pathlib import Path

from fontTools.ttLib import TTCollection

FONT = r"C:\Windows\Fonts\cambria.ttc"
OUT = Path(__file__).parent.parent / "src" / "study_mcp" / "cambria_math.py"

font = next(f for f in TTCollection(FONT).fonts if f["name"].getDebugName(4) == "Cambria Math")
glyph_ids = {name: i for i, name in enumerate(font.getGlyphOrder())}
cmap = font.getBestCmap()
char_of = {}
for codepoint, name in sorted(cmap.items()):
    char_of.setdefault(name, chr(codepoint))

# The "ssty" (script style) feature swaps a normal glyph for its small versions.
small = {}  # glyph id -> (character, level)
gsub = font["GSUB"].table
for record in gsub.FeatureList.FeatureRecord:
    if record.FeatureTag != "ssty":
        continue
    for index in record.Feature.LookupListIndex:
        for subtable in gsub.LookupList.Lookup[index].SubTable:
            subtable = getattr(subtable, "ExtSubTable", subtable)
            pairs = getattr(subtable, "alternates", None) or {
                base: [alt] for base, alt in getattr(subtable, "mapping", {}).items()
            }
            for base, alternates in pairs.items():
                for level, alt in enumerate(alternates, start=1):
                    if base in char_of:
                        small.setdefault(glyph_ids[alt], (char_of[base], level))

# A glyph number that is also a real character in this font is ambiguous; leave those alone.
small = {gid: v for gid, v in small.items() if gid not in cmap}

lines = [
    '"""Small (superscript/subscript) Cambria Math glyphs: glyph number -> (character, level).',
    "",
    "Generated by scripts/gen_cambria_math.py; do not edit by hand.",
    '"""',
    "",
    "SMALL_GLYPHS = {",
]
lines += [f"    0x{gid:04X}: ({char!r}, {level})," for gid, (char, level) in sorted(small.items())]
lines += ["}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"Wrote {len(small)} glyphs to {OUT}")
